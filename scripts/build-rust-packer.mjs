import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import {requireCargo} from "./rust-toolchain.mjs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = path.join(packageRoot, "native", "raster-packer", "Cargo.toml");
const cargo = requireCargo();
const runCargo = (args) =>
  execFileSync(cargo, args, {
    cwd: packageRoot,
    stdio: "inherit",
  });

const wasmOnly = process.argv.includes("--wasm-only");
const nativeOnly = process.argv.includes("--native-only");
if (!wasmOnly) {
  runCargo(["build", "--release", "--locked", "--manifest-path", manifest]);
}
if (!nativeOnly) {
  runCargo([
    "build",
    "--release",
    "--locked",
    "--target",
    "wasm32-unknown-unknown",
    "--lib",
    "--manifest-path",
    manifest,
  ]);
}

const targetRoot = path.join(packageRoot, "native", "raster-packer", "target");
let nativeTarget = "";
if (!wasmOnly) {
  const nativeName = process.platform === "win32" ? "dxf-raster-packer.exe" : "dxf-raster-packer";
  const nativeSource = path.join(targetRoot, "release", nativeName);
  nativeTarget = path.join(packageRoot, ".temp", "raster", nativeName);
  mkdirSync(path.dirname(nativeTarget), { recursive: true });
  copyFileSync(nativeSource, nativeTarget);
}

let wasmTarget = "";
if (!nativeOnly) {
  const wasmSource = path.join(
    targetRoot,
    "wasm32-unknown-unknown",
    "release",
    "dxf_raster_core.wasm",
  );
  wasmTarget = path.join(
    packageRoot,
    "vendor",
    "dxf-editor-v2",
    "src",
    "generated",
    "rust-packer-wasm.ts",
  );
  const wasmBase64 = readFileSync(wasmSource).toString("base64");
  writeFileSync(
    wasmTarget,
    `// Generated by scripts/build-rust-packer.mjs.\nexport const RUST_PACKER_WASM_BASE64 = ${JSON.stringify(wasmBase64)};\n`,
    "utf8",
  );
}

console.log(
  `Rust packer built: ${[nativeTarget, wasmTarget]
    .filter(Boolean)
    .map((target) => path.relative(packageRoot, target))
    .join(" and ")}`,
);
